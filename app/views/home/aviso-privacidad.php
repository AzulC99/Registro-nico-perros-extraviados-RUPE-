                <h1 class="fw-bold mb-2"><i class="bi bi-shield-lock me-2"></i>Aviso de Privacidad</h1>
                <p class="text-muted mb-4">Última actualización: septiembre 2026 · RUPE CDMX · UnADM</p>

                <p>El presente Aviso de Privacidad se emite en cumplimiento de la Ley General de Protección de Datos Personales en Posesión de Sujetos Obligados y la normatividad aplicable en la Ciudad de México, para informar sobre el tratamiento de los datos personales recabados a través de la plataforma <strong>RUPE CDMX</strong> (Registro Único de Mascotas Extraviadas).</p>

                <h2>1. Responsable del tratamiento</h2>
                <p>La Universidad Abierta y a Distancia de México (UnADM), a través del proyecto académico RUPE CDMX, es responsable del tratamiento de los datos personales recabados. Para ejercer derechos ARCO o consultas relacionadas con privacidad, puede contactar a través de los canales oficiales de la plataforma.</p>

                <h2>2. Datos personales que se recaban</h2>
                <ul>
                    <li>Datos de identificación y contacto del tutor/usuario (nombre, apellidos, correo electrónico, teléfono).</li>
                    <li>Datos de la mascota (nombre, especie, raza, color, sexo, edad aproximada, fotografías, folio de registro).</li>
                    <li>Datos de ubicación cuando el usuario reporta un avistamiento o utiliza funciones de geolocalización (previo consentimiento).</li>
                    <li>Datos técnicos de navegación (dirección IP, tipo de dispositivo, registros de acceso) con fines de seguridad y auditoría.</li>
                </ul>

                <h2>3. Finalidades del tratamiento</h2>
                <p><strong>Finalidades primarias:</strong></p>
                <ul>
                    <li>Registro y gestión de reportes de mascotas extraviadas o en búsqueda.</li>
                    <li>Generación de fichas públicas con código QR para facilitar la localización.</li>
                    <li>Comunicación entre tutores y personas que reportan avistamientos.</li>
                    <li>Autenticación, seguridad de la cuenta y cumplimiento de obligaciones legales.</li>
                </ul>
                <p><strong>Finalidades secundarias</strong> (opcionales, con consentimiento): envío de boletines informativos y mejora del servicio mediante estadísticas agregadas.</p>

                <h2>4. Transferencias</h2>
                <p>Los datos no se comercializan. Podrán compartirse únicamente con autoridades competentes cuando exista requerimiento legal o para la protección de la integridad de las personas o animales, o con proveedores tecnológicos necesarios para el funcionamiento de la plataforma (hosting, correo), bajo obligaciones de confidencialidad.</p>

                <h2>5. Derechos ARCO</h2>
                <p>Usted puede ejercer los derechos de Acceso, Rectificación, Cancelación y Oposición (ARCO), así como la limitación del uso o divulgación de sus datos, a través de la sección de perfil de la plataforma o mediante solicitud formal a los canales de contacto institucionales. Se dará respuesta en los plazos establecidos por la ley.</p>

                <h2>6. Medidas de seguridad</h2>
                <p>Se implementan medidas administrativas, técnicas y físicas para proteger los datos personales, incluyendo cifrado de contraseñas, control de acceso por roles, registro de auditoría y uso de reCAPTCHA para mitigar abusos automatizados.</p>

                <h2>7. Conservación</h2>
                <p>Los datos se conservarán mientras la cuenta permanezca activa y el reporte de la mascota esté vigente, o el tiempo necesario para cumplir obligaciones legales y de auditoría. Posteriormente se procederá a su eliminación o anonimización segura.</p>

                <h2>8. Cambios al aviso</h2>
                <p>Cualquier modificación al presente Aviso de Privacidad se publicará en esta misma página con la fecha de actualización correspondiente.</p>

                <p class="mt-4 text-muted small">Este documento es de carácter informativo y forma parte del marco de transparencia del proyecto RUPE CDMX desarrollado en el contexto académico de la UnADM y alineado con lineamientos de la Secretaría de Educación Pública (SEP).</p>
